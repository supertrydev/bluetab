const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const languages = ['en', 'tr', 'es', 'pt-BR', 'id', 'ar'];
const readLocale = (language) => JSON.parse(fs.readFileSync(path.join(root, 'src/i18n/locales', `${language}.json`), 'utf8'));
const toAsciiJson = (value) => JSON.stringify(value, null, 2).replace(/[^\x00-\x7F]/g,
  (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`);

function writeGenerated(name, value) {
  const file = path.join(root, 'src/i18n', name);
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== value) fs.writeFileSync(file, value);
}

function generateRuntimeResources() {
  const en = readLocale('en');
  writeGenerated('runtime-resources.ts', `// Generated by scripts/generate-runtime-resources.cjs.\nexport const EN_RESOURCES = ${toAsciiJson(en)} as const;\n`);
  const prefixes = new Set(['Session ', 'Saved ', 'Selected ', 'Suspended ']);
  for (const language of languages) {
    const templates = readLocale(language).contextMenu.generatedGroups;
    for (const key of ['session', 'suspended', 'selected', 'saved', 'savedSet']) {
      const prefix = templates[key]?.split('{{')[0];
      if (prefix?.trim()) prefixes.add(prefix);
    }
  }
  writeGenerated('generated-name-prefixes.ts', `// Generated by scripts/generate-runtime-resources.cjs.\nexport const AUTO_GENERATED_PREFIXES: readonly string[] = ${toAsciiJson([...prefixes])};\n`);
  const modalStrings = Object.fromEntries(Object.entries(en.brainDumpModal).map(([key, value]) => [`brainDumpModal.${key}`, value]));
  writeGenerated('brain-dump-strings.ts', `// Generated by scripts/generate-runtime-resources.cjs.\nexport const BRAIN_DUMP_STRINGS = ${toAsciiJson(modalStrings)} as const;\nexport type BrainDumpStrings = Record<keyof typeof BRAIN_DUMP_STRINGS, string>;\n`);
}

// Vite emits these as package files, never as JavaScript imports. Locale JSON
// remains the sole source for both the fallback and on-demand translations.
function getLocaleAssets() {
  return languages.filter((language) => language !== 'en').map((language) => ({
    fileName: `locales/${language}.json`,
    source: JSON.stringify(readLocale(language)),
  }));
}
module.exports = { generateRuntimeResources, getLocaleAssets };
if (require.main === module) generateRuntimeResources();
