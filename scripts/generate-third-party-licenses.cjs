#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const { dependencies } = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const entries = Object.keys(dependencies).sort().map((name) => {
  const metadata = JSON.parse(fs.readFileSync(path.join(root, 'node_modules', name, 'package.json'), 'utf8'));
  const licenses = metadata.license ?? metadata.licenses;
  const license = (Array.isArray(licenses) ? licenses : [licenses])
    .map((entry) => typeof entry === 'string' ? entry : entry?.type)
    .filter(Boolean)
    .join(' OR ');
  if (!metadata.version || !license) throw new Error(`Missing version or license for ${name}`);
  return { name, version: metadata.version, license };
});
const output = '// Generated by scripts/generate-third-party-licenses.cjs. Do not edit by hand.\n'
  + `export const THIRD_PARTY_LICENSES = ${JSON.stringify(entries, null, 2)} as const;\n`;
fs.writeFileSync(path.join(root, 'src/settings/third-party-licenses.ts'), output);
console.log(`Generated license metadata for ${entries.length} production dependencies.`);
