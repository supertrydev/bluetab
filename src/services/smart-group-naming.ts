import { Storage } from '../utils/storage';
import { suggestGroupName } from './ai-group-naming';
import type { TabGroup, TabItem } from '../types/models';
import { AUTO_GENERATED_PREFIXES } from '../i18n/generated-name-prefixes';

interface AutoRenameSavedGroupIfUntitledParams {
  groupId: string;
  initialName: string;
  tabs: TabItem[];
  isPro: boolean;
  onGroupsRenamed?: (groups: TabGroup[]) => void;
}

export function isAutoGeneratedGroupName(name: string): boolean {
  // The generated part is always a time, date or set number, so a name like
  // "Session notes" typed by the user is not treated as generated.
  return AUTO_GENERATED_PREFIXES.some((prefix) => name.startsWith(prefix) && /\d/.test(name.slice(prefix.length)));
}

export async function autoRenameSavedGroupIfUntitled({
  groupId,
  initialName,
  tabs,
  isPro,
  onGroupsRenamed,
}: AutoRenameSavedGroupIfUntitledParams): Promise<void> {
  if (!isPro || tabs.length < 2 || !isAutoGeneratedGroupName(initialName)) {
    return;
  }

  try {
    const suggestedName = (await suggestGroupName(
      tabs.map((tab) => ({ title: tab.title, url: tab.url })),
    ))?.trim();

    if (!suggestedName || suggestedName === initialName) {
      return;
    }

    const latestGroups = (await Storage.get<TabGroup[]>('groups')) ?? [];
    const targetGroup = latestGroups.find((group) => group.id === groupId);

    if (!targetGroup || targetGroup.name !== initialName) {
      return;
    }

    const renamedAt = Date.now();
    const updatedGroups = latestGroups.map((group) =>
      group.id === groupId
        ? { ...group, name: suggestedName, modified: renamedAt }
        : group,
    );

    await Storage.set('groups', updatedGroups);
    onGroupsRenamed?.(updatedGroups);
  } catch (error) {
    console.warn('[BlueTab][SmartGroupNaming] Failed to auto-rename saved group:', error);
  }
}
