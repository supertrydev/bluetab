import { Storage } from '../utils/storage';
import { suggestGroupName } from './ai-group-naming';
import { autoRenameSavedGroupIfUntitled, isAutoGeneratedGroupName } from './smart-group-naming';
import type { TabGroup, TabItem } from '../types/models';

jest.mock('../utils/storage');
jest.mock('./ai-group-naming', () => ({ suggestGroupName: jest.fn() }));

const mockStorageGet = Storage.get as jest.MockedFunction<typeof Storage.get>;
const mockStorageSet = Storage.set as jest.MockedFunction<typeof Storage.set>;
const mockSuggestGroupName = suggestGroupName as jest.MockedFunction<typeof suggestGroupName>;

const sampleTabs: TabItem[] = [
  {
    id: 'tab-1',
    title: 'React docs',
    url: 'https://react.dev',
    timestamp: Date.now(),
    groupId: 'group-1',
  },
  {
    id: 'tab-2',
    title: 'Vue docs',
    url: 'https://vuejs.org',
    timestamp: Date.now(),
    groupId: 'group-1',
  },
];

describe('autoRenameSavedGroupIfUntitled()', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    mockStorageGet.mockResolvedValue([]);
    mockStorageSet.mockResolvedValue(undefined);
    mockSuggestGroupName.mockResolvedValue(null);
  });

  it('renames a saved group when the original placeholder name is still unchanged', async () => {
    const initialName = 'Session 6/2/2026, 10:00:00 PM';
    const groups: TabGroup[] = [
      {
        id: 'group-1',
        name: initialName,
        tabs: sampleTabs,
        created: Date.now(),
        modified: Date.now(),
      },
    ];
    mockStorageGet.mockResolvedValue(groups);
    mockSuggestGroupName.mockResolvedValue('Frontend Frameworks');

    const onGroupsRenamed = jest.fn();

    await autoRenameSavedGroupIfUntitled({
      groupId: 'group-1',
      initialName,
      tabs: sampleTabs,
      isPro: true,
      onGroupsRenamed,
    });

    expect(mockSuggestGroupName).toHaveBeenCalledWith([
      { title: 'React docs', url: 'https://react.dev' },
      { title: 'Vue docs', url: 'https://vuejs.org' },
    ]);
    expect(mockStorageSet).toHaveBeenCalledWith(
      'groups',
      expect.arrayContaining([
        expect.objectContaining({ id: 'group-1', name: 'Frontend Frameworks' }),
      ]),
    );
    expect(onGroupsRenamed).toHaveBeenCalledWith(
      expect.arrayContaining([
        expect.objectContaining({ id: 'group-1', name: 'Frontend Frameworks' }),
      ]),
    );
  });

  it('does not rename when the saved group name was already changed by something else', async () => {
    mockStorageGet.mockResolvedValue([
      {
        id: 'group-1',
        name: 'My Custom Group',
        tabs: sampleTabs,
        created: Date.now(),
        modified: Date.now(),
      },
    ]);
    mockSuggestGroupName.mockResolvedValue('Frontend Frameworks');

    await autoRenameSavedGroupIfUntitled({
      groupId: 'group-1',
      initialName: 'Session 6/2/2026, 10:00:00 PM',
      tabs: sampleTabs,
      isPro: true,
      onGroupsRenamed: jest.fn(),
    });

    expect(mockStorageSet).not.toHaveBeenCalled();
  });

  it('skips AI completely when the initial group name is not an untitled session placeholder', async () => {
    await autoRenameSavedGroupIfUntitled({
      groupId: 'group-1',
      initialName: 'Research Stack',
      tabs: sampleTabs,
      isPro: true,
      onGroupsRenamed: jest.fn(),
    });

    expect(mockSuggestGroupName).not.toHaveBeenCalled();
    expect(mockStorageSet).not.toHaveBeenCalled();
  });
});

describe('isAutoGeneratedGroupName()', () => {
  it('treats Session, Saved, and Selected prefixes as AI-rename candidates', () => {
    expect(isAutoGeneratedGroupName('Session 10:00 PM')).toBe(true);
    expect(isAutoGeneratedGroupName('Saved 6/2/2026')).toBe(true);
    expect(isAutoGeneratedGroupName('Selected 6/2/2026')).toBe(true);
    expect(isAutoGeneratedGroupName('Pinned Tabs')).toBe(false);
    expect(isAutoGeneratedGroupName('Research Stack')).toBe(false);
  });
});


describe('isAutoGeneratedGroupName() — translated names', () => {
  it('recognises generated names in every supported language', () => {
    expect(isAutoGeneratedGroupName('Oturum 14:30')).toBe(true);
    expect(isAutoGeneratedGroupName('Sesión 14:30')).toBe(true);
    expect(isAutoGeneratedGroupName('Sessão 14:30')).toBe(true);
    expect(isAutoGeneratedGroupName('Sesi 14.30')).toBe(true);
    expect(isAutoGeneratedGroupName('جلسة 14:30')).toBe(true);
    expect(isAutoGeneratedGroupName('Kaydedilenler 3 Eki 2026')).toBe(true);
    expect(isAutoGeneratedGroupName('Saved Set 2')).toBe(true);
    expect(isAutoGeneratedGroupName('Suspended 9:05 AM')).toBe(true);
  });

  it('still leaves user-named groups alone', () => {
    expect(isAutoGeneratedGroupName('Oturum notlar\u0131')).toBe(false);
    expect(isAutoGeneratedGroupName('Research')).toBe(false);
  });
});
